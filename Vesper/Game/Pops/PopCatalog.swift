import Foundation

// The full catalog of 100 pops, authored against the standard in
// PopStandard.swift (rules and value envelopes: docs/pop_standard.md).
//
// Pop #001 "Vesper" codifies the original v1.0 pop exactly — its numbers are
// sourced from GameConfig and the original palette so the classic experience
// is preserved byte-for-byte. Every other pop is a variation expressed purely
// as data. Numbers are stable forever; new pops append, never renumber.
//
// Progression design: docs/pop_progression.md · points: docs/pop_points.md

enum PopCatalog {

    // MARK: - Lookup

    static let all: [PopDefinition] = entries

    static let byNumber: [Int: PopDefinition] =
        Dictionary(uniqueKeysWithValues: all.map { ($0.number, $0) })

    static var classic: PopDefinition { byNumber[1]! }

    static func definition(for number: Int) -> PopDefinition {
        byNumber[number] ?? classic
    }

    // MARK: - Authoring helpers

    private static func c(_ r: Double, _ g: Double, _ b: Double) -> PopColor {
        PopColor(r: r / 255, g: g / 255, b: b / 255)
    }

    // a paint whose glow is derived from its fill, slightly deepened
    private static func pv(_ r: Double, _ g: Double, _ b: Double) -> PopPaint {
        PopPaint(fill: c(r, g, b), glow: c(r * 0.93, g * 0.89, b * 0.95))
    }

    // Every parameter defaults to the classic pop, so entries only state
    // what makes them different.
    private static func def(
        _ number: Int, _ name: String, _ family: PopFamily, _ rarity: PopRarity,
        flavor: String,
        paints: [PopPaint],
        shape: ParticleShape = .dot,
        pSize: ClosedRange<Double> = 1.2...3.4,
        halo: Double = 0.18,
        highlight: Double = 0.14,
        shimmer: Bool = false,
        pCount: Int = GameConfig.particleBaseCount,
        pSpeed: ClosedRange<Double> = 1.2...6,
        gravity: Double = Double(GameConfig.particleGravity),
        freq: Double = 460, spread: Double = 420, sweep: Double = 0.55,
        dur: Double = 0.14, sDecay: Double = 7.5, bright: Double = 0,
        hBase: Double = 0.35, hSize: Double = 0.5, sharp: Bool = false,
        rings: Int = 1,
        ringR: Double = Double(GameConfig.ringBaseMaxRadius),
        ringRK: Double = Double(GameConfig.ringRadiusPerOrbRadius),
        grow: Double = Double(GameConfig.ringGrowthFactor),
        growLin: Double = Double(GameConfig.ringGrowthLinear),
        shell: Double = Double(GameConfig.ringShellThickness),
        disarm: Double = Double(GameConfig.ringDisarmFraction),
        ringDecay: Double = Double(GameConfig.ringLifeDecay),
        unlock: UnlockRule
    ) -> PopDefinition {
        PopDefinition(
            number: number, name: name, family: family, rarity: rarity,
            flavor: flavor,
            style: PopStyle(paints: paints, particleShape: shape,
                            particleSizeRange: pSize, haloOpacity: halo,
                            highlightOpacity: highlight, shimmer: shimmer),
            behavior: PopBehavior(
                particleCountBase: pCount, particleSpeedRange: pSpeed,
                particleGravity: gravity,
                sound: SoundProfile(startFreq: freq, freqSpread: spread,
                                    sweep: sweep, duration: dur,
                                    decay: sDecay, brightness: bright),
                haptic: HapticProfile(baseIntensity: hBase,
                                      intensityPerSize: hSize, sharp: sharp)),
            chain: ChainBehavior(
                ringCount: rings, maxRadiusBase: ringR,
                maxRadiusPerOrbRadius: ringRK, growthFactor: grow,
                growthLinear: growLin, shellThickness: shell,
                disarmFraction: disarm, lifeDecay: ringDecay),
            unlock: unlock)
    }

